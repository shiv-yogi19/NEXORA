import sys, json, re, urllib.request
from playwright.sync_api import sync_playwright
S=sys.argv[1]  # scratch dir for screenshots and temp files; import os; PW=os.environ["NEXORA_TEST_PASSWORD"]
B="http://localhost:8080/?api=http://localhost:8787"
errs=[]
def ok(name, cond, extra=""): print(("PASS " if cond else "FAIL ")+name, extra)
with sync_playwright() as p:
    b=p.chromium.launch(args=["--autoplay-policy=no-user-gesture-required"])
    ctx=b.new_context(viewport={"width":1440,"height":900}, accept_downloads=True, permissions=["clipboard-read","clipboard-write"])
    pg=ctx.new_page()
    pg.on("console", lambda m: errs.append((m.type, m.text)) if m.type=="error" and "fonts" not in m.text and "TUNNEL" not in m.text else None)
    pg.on("pageerror", lambda e: errs.append(("pageerror", str(e))))
    pg.goto(B); pg.click("#intro-skip"); pg.wait_for_selector("#login-screen:not([hidden])")
    pg.fill("#login-password",PW); pg.click("#login-submit"); pg.wait_for_selector("#app:not([hidden])")
    # ---- video
    pg.goto(B+"#/movies"); pg.wait_for_selector(".card")
    pg.click(".card:has-text('demo.webm') .card-main"); pg.wait_for_selector("video")
    pg.wait_for_function  # noqa
    pg.wait_for_timeout(1500)
    vs=pg.eval_on_selector("video","v=>({rs:v.readyState,d:v.duration,err:v.error&&v.error.code,seekable:v.seekable.length&&v.seekable.end(0)})")
    ok("video loads", vs["rs"]>=1 and vs["d"]>10, vs)
    pg.eval_on_selector("video","v=>{v.muted=true;return v.play()}")
    pg.wait_for_timeout(500)
    pg.eval_on_selector("video","v=>{v.currentTime=12}")
    pg.wait_for_timeout(1200)
    ct=pg.eval_on_selector("video","v=>v.currentTime")
    ok("video seek (Range)", 11.5<ct<16, ct)
    pg.screenshot(path=S+"/s_watch.png")
    pg.wait_for_timeout(2500)
    pg.goto(B+"#/home"); pg.wait_for_timeout(1500); pg.click("button:has-text('Refresh')"); pg.wait_for_timeout(1000)
    ok("continue watching appears after progress", "Continue watching" in pg.inner_text("#main"))
    # ---- music
    pg.goto(B+"#/music"); pg.wait_for_selector(".card")
    pg.click(".card:has-text('tone3.ogg') .card-main"); pg.wait_for_selector("#miniplayer:not([hidden])")
    pg.wait_for_timeout(1500)
    pg.wait_for_timeout(1500)
    st=pg.eval_on_selector("#miniplayer","m=>({btns:[...m.querySelectorAll('button')].map(b=>b.getAttribute('aria-label')),seek:m.querySelector('input[aria-label=Seek]').value,txt:m.innerText})")
    ok("audio playing (mini player shows Pause + progress)", "Pause" in st["btns"] and int(st["seek"])>0, st)
    pg.screenshot(path=S+"/s_mini.png")
    pg.click("#miniplayer .mini-info") if pg.query_selector("#miniplayer .mini-info") else None
    pg.wait_for_timeout(700); pg.screenshot(path=S+"/s_expanded.png")
    pg.keyboard.press("Escape")
    # ---- photos
    pg.goto(B+"#/photos"); pg.wait_for_selector(".card")
    pg.click(".card-main"); pg.wait_for_selector(".viewer")
    pg.wait_for_timeout(700)
    t0=pg.inner_text(".viewer-bar .title")
    pg.keyboard.press("ArrowRight"); pg.wait_for_timeout(300)
    t1=pg.inner_text(".viewer-bar .title")
    ok("photo next", t0!=t1, (t0,t1))
    pg.click("[aria-label='Rotate']"); pg.click("[aria-label='Zoom in']")
    tf=pg.eval_on_selector(".stage img","i=>i.style.transform")
    ok("photo rotate+zoom", "rotate(90deg)" in tf and "scale(" in tf, tf)
    pg.screenshot(path=S+"/s_viewer.png")
    pg.click("[aria-label='Start slideshow']"); pg.wait_for_timeout(300)
    ok("slideshow button toggles", pg.query_selector("[aria-label='Stop slideshow']") is not None)
    pg.keyboard.press("Escape"); pg.wait_for_selector(".viewer", state="detached")
    # ---- documents
    pg.goto(B+"#/documents"); pg.wait_for_selector(".card")
    pg.click("text=note.txt"); pg.wait_for_selector(".doctext")
    pg.wait_for_timeout(600)
    ok("text doc shows contents", "hello nexora" in pg.inner_text(".doctext"))
    pg.keyboard.press("Escape")
    pg.click("text=doc.pdf"); pg.wait_for_selector("iframe.docframe"); ok("pdf viewer iframe", True)
    pg.click(".sheet [aria-label='Close']"); pg.wait_for_selector(".scrim", state="detached")
    # ---- favorites
    pg.goto(B+"#/photos"); pg.wait_for_selector(".card")
    pg.screenshot(path=S+"/dbg.png"); print(pg.inner_text("#main")[:200].replace("\n","|"), pg.eval_on_selector_all(".card button","els=>els.map(e=>e.getAttribute('aria-label'))"))
    pg.click(".card >> nth=0 >> [aria-label$='Favorites']", timeout=5000); pg.wait_for_timeout(600)
    pg.goto(B+"#/favorites"); pg.wait_for_selector(".card")
    ok("favorite persisted", "p1.jpg" in pg.inner_text("#main"))
    # ---- upload
    open(S+"/up1.txt","w").write("uploaded by playwright\n"); open(S+"/bad.exe","wb").write(b"MZ")
    pg.goto(B+"#/uploads"); pg.wait_for_selector(".drop")
    pg.select_option("#up-dest","Documents")
    pg.set_input_files("input[type=file]",[S+"/up1.txt", S+"/bad.exe"])
    pg.wait_for_selector("#main >> text=/Stored/", timeout=8000); pg.wait_for_timeout(800)
    txt=pg.inner_text("#main")
    ok("upload stored", "Stored" in txt and "Not scanned for malware" in txt)
    ok("bad extension rejected client-side", "not allowed" in txt, "")
    pg.goto(B+"#/documents"); pg.wait_for_selector(".card"); ok("uploaded file in library", "up1.txt" in pg.inner_text("#main"))
    # ---- share
    pg.goto(B+"#/shares"); pg.wait_for_selector("text=New share"); pg.click("text=New share")
    pg.wait_for_selector(".sheet input[type=search]"); pg.wait_for_selector(".sheet .rowitem"); pg.click(".sheet .rowitem >> nth=0")
    pg.wait_for_selector("text=Create link"); pg.click("text=Create link")
    pg.wait_for_selector(".linkbox input"); link=pg.input_value(".linkbox input")
    ok("share link created", "/api/v1/s/" in link, link[:60])
    r=urllib.request.urlopen(link); ok("public link works w/o login", r.status==200, r.status)
    pg.keyboard.press("Escape"); pg.goto(B+"#/shares"); pg.wait_for_selector(".badge:has-text('Active')")
    pg.once("dialog", lambda d: d.accept()); pg.click("button:has-text('Revoke') >> nth=0"); pg.wait_for_selector(".badge:has-text('Revoked')")
    try: urllib.request.urlopen(link); ok("revoked link blocked", False)
    except Exception as e: ok("revoked link blocked", "40" in str(e), str(e))
    # ---- server/storage
    pg.goto(B+"#/server"); pg.wait_for_selector("text=Mobile Server"); pg.wait_for_timeout(800)
    print(pg.inner_text("#main")[:900].replace("\n"," | "))
    pg.screenshot(path=S+"/s_server.png")
    print("ERRORS:", json.dumps(errs,indent=1)[:2500])
    b.close()
